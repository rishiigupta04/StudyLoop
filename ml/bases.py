"""Hand-written base utterances for the Tier 1c classifier: 20 per intent x {en, hinglish, hi}.

These are the bases the synthetic set is built from, alongside `backend/tests/voice_corpus.py`. Unlike the
corpus (which the regex classifier was tuned on, so it only ever goes to TRAIN), these were written for this
pipeline and are split by base into train / val / test. Paraphrases inherit their base's split
(`dataset.py`), so no paraphrase of a test base is ever trained on.

Labels follow the rules at the top of backend/tests/voice_corpus.py, plus two for off-topic speech:
- a topic named -> SEMANTIC_SEEK ("I missed the bit where he defined X"); no topic -> REPLAY ("I missed that")
- "I didn't hear / catch that" -> REPLAY; "I didn't understand / get it" -> ASK
- "I can't hear" (now) -> VOLUME up; "sunai nahi diya" (just now) -> REPLAY
- complaints invert the adjective: "too fast" -> SPEED down, "too loud" -> VOLUME down
- undo / "where I was", restart, the end / middle / N% -> SEEK_ABSOLUTE
- a question that merely contains command words is ASK; "what did he say about X" asks about X -> ASK
- acknowledgements that end an exchange ("thanks", "got it", "theek hai") -> STOP_SPEAKING; a bare "stop" -> PAUSE
- "don't stop / mat roko" -> PLAY; any other negated command ("don't skip", "speed mat badlo") -> OOS
- help ("what can I say"), greetings, off-topic questions (weather, time, food), talk aimed at someone else in
  the room, muttering, half sentences and false starts -> OOS. A question about the lecture is ASK.

Styles, i.e. what the classifier sees after hosted STT (roadmap D14) and before `normalize()`:
- en: English as Sarvam / Groq write it (digits for numbers, some fillers).
- hinglish: Hindi in Latin letters, the way Groq Whisper romanizes it (spellings vary on purpose).
- hi: Sarvam Saaras codemix: Hindi in Devanagari, English words mostly in Latin ("video को pause करो"),
  numbers as digits. Some are pure Devanagari (Chrome hi-IN, or Sarvam writing an English term in Devanagari).
The hi bases are deliberately NOT translations of the hinglish ones: after `normalize()` both scripts land in the
same Latin form, so mirrored pairs would collapse into duplicates.
"""

